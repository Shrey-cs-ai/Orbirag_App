# Gemini helper — goes through the fallback chain
async def _ask_gemini(prompt: str, json_mode: bool = False) -> str:
    from services.ai_service import _generate_with_fallback
    return await _generate_with_fallback(prompt, json_mode=json_mode)


def _split_sentences(text: str) -> List[str]:
    # Simple, robust sentence splitter
    text = re.sub(r'\s+', ' ', text.strip())
    parts = re.split(r'(?<=[.!?])\s+', text)
    sentences = [p.strip() for p in parts if len(p.strip()) > 15]
    if not sentences and len(text.strip()) > 5:
        sentences = [text.strip()]
    return sentences


def _cosine(a, b):
    a = np.asarray(a, dtype=np.float32)
    b = np.asarray(b, dtype=np.float32)
    denom = (np.linalg.norm(a) * np.linalg.norm(b)) or 1e-9
    return float(np.dot(a, b) / denom)


async def _detect_ai_likelihood(text: str) -> dict:
    prompt = f"""You are an academic text integrity analyst. Analyze the following text to estimate the probability (0-100%) that it was generated by an AI model (like ChatGPT, Claude, etc.) versus written by a human.
Consider indicators such as uniform sentence structure and length, overuse of transitional adverbs, generic academic tone without personal or specific empirical nuances, and perplexity/burstiness patterns.

Return ONLY a valid JSON object:
{{
  "ai_likelihood_score": <integer from 0 to 100>,
  "ai_likelihood_explanation": "<concise 1-2 sentence explanation of the assessment>"
}}

TEXT TO ANALYZE:
{text[:2500]}
"""
    try:
        from services.ai_service import _generate_with_fallback
        raw = await _generate_with_fallback(prompt, json_mode=True)
        raw = (raw or "").strip()
        if raw.startswith("```"):
            raw = raw.strip("`")
            if raw.startswith("json"):
                raw = raw[4:]
        data = json.loads(raw)
        score = int(data.get("ai_likelihood_score", 0))
        score = max(0, min(100, score))
        explanation = str(data.get("ai_likelihood_explanation", ""))
        return {
            "ai_likelihood_score": score,
            "ai_likelihood_explanation": explanation or "This text contains patterns commonly associated with AI generation. This is not definitive proof.",
        }
    except Exception as e:
        print(f"[Plagiarism] AI likelihood detection failed: {e}")
        return {
            "ai_likelihood_score": 50,
            "ai_likelihood_explanation": "AI detection is probabilistic and should not be treated as definitive proof.",
        }


async def _fetch_openalex_papers(query: str, limit: int = 15) -> List[dict]:
    import httpx
    clean_query = re.sub(r'[\(\)]', ' ', query)
    clean_query = re.sub(r'\b(AND|OR|NOT)\b', ' ', clean_query)
    clean_query = " ".join(clean_query.split())[:120]

    url = "https://api.openalex.org/works"
    params = {"search": clean_query, "per_page": limit}
    papers = []
    try:
        async with httpx.AsyncClient(timeout=12.0) as client:
            resp = await client.get(url, params=params)
            if resp.status_code == 200:
                for item in resp.json().get("results", []):
                    title = item.get("title") or "Untitled"
                    year = str(item.get("publication_year") or "n.d.")
                    authorships = item.get("authorships") or []
                    author_names = [
                        a.get("author", {}).get("display_name")
                        for a in authorships
                        if a.get("author") and a.get("author", {}).get("display_name")
                    ]

                    if not author_names:
                        source_author = "Unknown"
                        citation_authors = "Unknown"
                    elif len(author_names) == 1:
                        source_author = author_names[0].split()[-1]
                        citation_authors = author_names[0]
                    elif len(author_names) == 2:
                        s1 = author_names[0].split()[-1]
                        s2 = author_names[1].split()[-1]
                        source_author = f"{s1} & {s2}"
                        citation_authors = f"{author_names[0]} & {author_names[1]}"
                    else:
                        s1 = author_names[0].split()[-1]
                        source_author = f"{s1} et al."
                        citation_authors = f"{author_names[0]}, et al."

                    inv = item.get("abstract_inverted_index")
                    abstract = ""
                    if inv:
                        words = sorted([(pos, w) for w, poses in inv.items() for pos in poses])
                        abstract = " ".join([w for _, w in words])

                    if not abstract or len(abstract) < 60:
                        continue

                    venue = (
                        item.get("primary_location", {}).get("source", {}).get("display_name")
                        if item.get("primary_location") and item.get("primary_location", {}).get("source")
                        else ""
                    )
                    citation_string = f"{citation_authors} ({year}). {title}."
                    if venue:
                        citation_string += f" {venue}."

                    papers.append({
                        "title": title,
                        "year": year,
                        "source_author": source_author,
                        "citation_string": citation_string,
                        "abstract": abstract,
                    })
    except Exception as e:
        print(f"[Plagiarism] OpenAlex fetch error: {e}")
    return papers


async def analyze_text(text: str) -> dict:
    """
    Real plagiarism and AI likelihood detection pipeline.
    """
    import asyncio
    import os
    os.environ["HF_HUB_OFFLINE"] = "1"
    from services.ai_service import build_search_query
    from services.search_service import search_semantic_scholar
    from services.embedding_service import embed_texts

    sentences = _split_sentences(text)
    if not sentences:
        return {
            "similarity_score": 0,
            "ai_likelihood_score": 0,
            "ai_likelihood_explanation": "Insufficient text provided for analysis.",
            "matches": [],
        }

    # 1. Concurrently run AI likelihood assessment
    ai_task = asyncio.create_task(_detect_ai_likelihood(text))

    # 2. Extract academic query keywords
    try:
        keywords_data = await build_search_query(text[:1500])
    except Exception as e:
        print(f"[Plagiarism] Query extraction failed: {e}")
        keywords_data = None

    if keywords_data and keywords_data.get("boolean_query"):
        query = keywords_data["boolean_query"]
    elif keywords_data and keywords_data.get("keywords"):
        query = " ".join(keywords_data["keywords"][:4])
    else:
        query = " ".join(sentences[0].split()[:8])

    # 3. Retrieve reference papers (Semantic Scholar with OpenAlex fallback)
    papers = []
    try:
        s2_papers = await search_semantic_scholar(query=query, limit=20)
        for p in s2_papers:
            abs_text = p.get("abstract") or ""
            if len(abs_text) > 80:
                raw_authors = p.get("authors") or ""
                authors_list = [a.strip() for a in raw_authors.split(",") if a.strip()]
                if not authors_list:
                    source_author = "Unknown"
                elif len(authors_list) == 1:
                    source_author = authors_list[0].split()[-1]
                else:
                    source_author = f"{authors_list[0].split()[-1]} et al."
                y = str(p.get("year") or "n.d.")
                t = p.get("title") or "Untitled"
                papers.append({
                    "title": t,
                    "year": y,
                    "source_author": source_author,
                    "citation_string": f"{raw_authors} ({y}). {t}.",
                    "abstract": abs_text,
                })
    except Exception as e:
        print(f"[Plagiarism] S2 search failed: {e}")

    # Fallback to OpenAlex if S2 returned 0 papers with abstracts
    if not papers:
        papers = await _fetch_openalex_papers(query, limit=20)

    # 4. Await AI likelihood result
    ai_result = await ai_task

    # 5. Sentence embeddings & matching
    matches = []
    flagged_indices = set()
    THRESHOLD = 0.60

    if papers:
        try:
            sentence_vecs = embed_texts(sentences)
            paper_chunks = []
            paper_meta = []
            for p in papers:
                abs_sents = [s.strip() for s in re.split(r'(?<=[.!?])\s+', p["abstract"]) if len(s.strip()) > 15]
                for s in abs_sents:
                    paper_chunks.append(s)
                    paper_meta.append(p)

            if paper_chunks:
                chunk_vecs = embed_texts(paper_chunks)
                for i, s_vec in enumerate(sentence_vecs):
                    best_score = 0.0
                    best_paper = None
                    for j, c_vec in enumerate(chunk_vecs):
                        sim = _cosine(s_vec, c_vec)
                        if sim > best_score:
                            best_score = sim
                            best_paper = paper_meta[j]

                    if best_score >= THRESHOLD and best_paper is not None:
                        flagged_indices.add(i)
                        sim_pct = int(round(best_score * 100))
                        matches.append({
                            "id": f"match_{len(matches) + 1}",
                            "text": sentences[i],
                            "similarity_percentage": sim_pct,
                            "source_title": best_paper["title"],
                            "source_author": best_paper["source_author"],
                            "source_year": str(best_paper["year"]),
                            "citation_string": best_paper["citation_string"],
                        })
        except Exception as e:
            print(f"[Plagiarism] Embedding comparison failed: {e}")

    # 6. Overall similarity score calculation
    total_sentences = len(sentences)
    if matches:
        avg_match_sim = sum(m["similarity_percentage"] for m in matches) / len(matches)
        overall_similarity = int(round((len(flagged_indices) / total_sentences) * avg_match_sim))
        overall_similarity = max(1, min(100, overall_similarity))
    else:
        overall_similarity = 0

    return {
        "similarity_score": overall_similarity,
        "ai_likelihood_score": ai_result["ai_likelihood_score"],
        "ai_likelihood_explanation": ai_result["ai_likelihood_explanation"],
        "matches": matches,
    }


# Paraphrase / Humanize
_PROMPTS = {
    "paraphrase": """You are an academic writing assistant. Paraphrase the text below
to reduce plagiarism while preserving meaning. Use different vocabulary and
sentence structure. Keep it academic and formal. Return ONLY the rewritten text —
no explanations, no quotes.

TEXT:
{text}

PARAPHRASED:""",

    "humanize": """You are an academic writing assistant. Rewrite the text below
to sound more natural, human, and less AI-generated. Use varied sentence lengths
and natural transitions. Preserve the original meaning. Return ONLY the rewritten
text — no explanations.

TEXT:
{text}

HUMANIZED:""",
}


async def rewrite_text(text: str, mode: str) -> str:
    if mode not in _PROMPTS:
        raise ValueError(f"Invalid mode: {mode}")
    prompt = _PROMPTS[mode].format(text=text)
    return (await _ask_gemini(prompt)).strip()


def format_citation(source: str, year: str = "2023", style: str = "APA 7") -> str:
    source = (source or "").strip()
    year = (year or "n.d.").strip()
    if not source:
        return ""

    # Case 1: single author "Ganeju, S."
    m = re.match(r"^([A-Z][A-Za-z'\-]+),\s*[A-Z]\.", source)
    if m and source.count(",") == 1:
        return f"({m.group(1)}, {year})"

    # Case 2: multi-author "Ganeju, S., Subedi, A., ..."
    m = re.match(r"^([A-Z][A-Za-z'\-]+),", source)
    if m:
        return f"({m.group(1)} et al., {year})"

    # Case 3: title — skip stopwords, take first meaningful word
    stopwords = {"a", "an", "the", "of", "in", "on", "for", "and", "or",
                 "to", "at", "by", "with", "is", "are", "be", "using",
                 "based", "designing", "towards", "toward", "from",
                 "into", "over", "under"}
    for w in re.findall(r"[A-Za-z][A-Za-z'\-]+", source):
        if w.lower() not in stopwords and len(w) > 2:
            return f"({w}, {year})"

    return f"({source}, {year})"


# DB CRUD
def save_check(
    db: Session,
    text: str,
    similarity_score: str,
    matches: List[dict],
    user_id: Optional[str] = None,
) -> PlagiarismCheck:
    row = PlagiarismCheck(
        document_text=text,
        similarity_score=str(similarity_score),
        matches=matches,
        user_id=user_id,
    )
    db.add(row)
    db.commit()
    db.refresh(row)
    return row


def list_checks(db: Session, user_id: Optional[str] = None) -> List[PlagiarismCheck]:
    q = db.query(PlagiarismCheck)
    if user_id:
        q = q.filter(PlagiarismCheck.user_id == user_id)
    return q.order_by(desc(PlagiarismCheck.created_at)).all()


def get_check(db: Session, check_id) -> Optional[PlagiarismCheck]:
    try:
        uid = UUID(str(check_id))
    except (ValueError, AttributeError):
        return None
    return db.query(PlagiarismCheck).filter(PlagiarismCheck.id == uid).first()


def delete_check(db: Session, check_id) -> bool:
    row = get_check(db, check_id)
    if not row:
        return False
    db.delete(row)
    db.commit()
    return True